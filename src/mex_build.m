function mex_build()
    % Output directory
    outDir = fullfile('.', 'mexfunc');
    if ~exist(outDir, 'dir')
        mkdir(outDir);
    end

    % Detect GPU arch (e.g., 86 -> RTX 30xx series)
    arch = strrep(gpuDevice().ComputeCapability, '.', '');
    nvcc_flag = ['NVCCFLAGS=-gencode=arch=compute_' arch ',code=sm_' arch];

    % Compile all .cu files
    sources = { ...
        'CreateSimulation.cu', ...
        'SetConst.cu', ...
        'ReadySimulation.cu', ...
        'InitField.cu', ...
        'SetAntennaLocations.cu', ...
        'SetSource.cu', ...
        'DeleteSimulation.cu', ...
        'ResetFieldAll.cu', ...
        'OutputAnt.cu', ...
        'OutputVis.cu', ...
        'Init1D.cu', ...
        'UpdateMaterial.cu', ...
        'UpdateH_All.cu', ...
        'UpdateH_PML.cu', ...
        'UpdateE_All.cu', ...
        'UpdateE_PML.cu', ...
        'CoaxUpdate.cu', ...
        'CreateMu.cu', ...
        'UpdateH_PlaneWave.cu', ...
        'UpdateE_PlaneWave.cu', ...
        'UpdateCuda.cu'};

    for k = 1:length(sources)
        [~,name] = fileparts(sources{k});
        fprintf('Building %s...\n', name);

        if strcmp(name,'Gradient_calculation_all')
            mexcuda('-output', fullfile(outDir,name), ...
                nvcc_flag, ...
                'CXXFLAGS=$CXXFLAGS -fopenmp', ...
                'LDFLAGS=$LDFLAGS -fopenmp', ...
                fullfile('src',sources{k}));
        else
            mexcuda('-output', fullfile(outDir,name), ...
                nvcc_flag, ...
                fullfile('src',sources{k}));
        end
    end

    fprintf('✅ All MEX files built into %s\n', outDir);
end
